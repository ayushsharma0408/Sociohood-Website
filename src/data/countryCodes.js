export const findCountryByDial = (dial) =>
  COUNTRY_CODES.find((country) => country.dial === dial) ||
  COUNTRY_CODES.find((country) => country.dial === DEFAULT_COUNTRY_CODE);

export const searchCountries = (query) => {
  const normalized = query.trim().toLowerCase().replace(/\s+/g, " ");
  if (!normalized) return COUNTRY_CODES;

  const digits = normalized.replace(/[^\d+]/g, "");

  return COUNTRY_CODES.filter((country) => {
    if (country.name.toLowerCase().includes(normalized)) return true;
    if (country.iso.toLowerCase() === normalized) return true;
    if (country.dial.includes(digits) && digits.length > 0) return true;
    if (country.aliases?.some((alias) => alias.includes(normalized) || normalized.includes(alias))) {
      return true;
    }
    return false;
  });
};
